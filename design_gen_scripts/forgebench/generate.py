def expression(text, defines):
    node = ast.parse(text, mode="eval").body

    def resolve(n):
        if isinstance(n, ast.Constant) and isinstance(n.value, int):
            return n.value
        if isinstance(n, ast.Name):
            return expression(defines[n.id], defines)
        if isinstance(n, ast.BinOp):
            op = {ast.Add: operator.add, ast.Sub: operator.sub, ast.Mult: operator.mul}[
                type(n.op)
            ]
            return op(resolve(n.left), resolve(n.right))
        raise ValueError(f"Unsupported dimension: {text}")

    return resolve(node)


def interface(design):
    source = (design / "top.cpp").read_text()
    header = (design / "top.h").read_text()
    source = re.sub(r"/\*.*?\*/|//[^\n]*", "", source, flags=re.S)
    defines = dict(
        re.findall(r"^\s*#define\s+(\w+)\s+([^\n/]+)", header + "\n" + source, re.M)
    )
    signature = re.search(r"\bvoid\s+top\s*\((.*?)\)\s*\{", source, re.S)
    if signature is None:
        raise ValueError(f"No top definition: {design}")
    arrays = {}
    for argument in signature[1].split(","):
        match = re.fullmatch(r"\s*data_t\s+(\w+)\s*((?:\[[^]]+\]\s*)+)\s*", argument)
        if match is None:
            raise ValueError(f"Unsupported top argument: {argument}")
        arrays[match[1]] = [
            expression(d, defines) for d in re.findall(r"\[([^]]+)\]", match[2])
        ]
    return arrays


def render_testbench(arrays, inputs, outputs, data_type="ap_fixed<16, 5>"):
    def decl(key):
        return "data_t " + key + "".join(f"[{n}]" for n in arrays[key])

    lines = [
        "// Generated by design_gen_scripts/forgebench/generate.py.",
        "#include <ap_fixed.h>",
        '#include "tb_support.h"',
        f"typedef {data_type} data_t;",
        "// Match the generated kernel interface.",
        "void top(" + ", ".join(decl(k) for k in arrays) + ");",
        "",
    ]
    lines += ["static " + decl(k) + ";" for k in arrays]
    lines += ["", "int main() {", "    try {"]
    for key, filename in inputs.items():
        lines += [
            f'        forge_tb::load({key}, "{filename}", {math.prod(arrays[key])});'
        ]
    for key, filename in outputs.items():
        lines += [
            f'        const std::vector<double> golden_{key} = forge_tb::read("{filename}", {math.prod(arrays[key])});',
            f"        forge_tb::poison({key}, golden_{key});",
        ]
    lines += ["        top(" + ", ".join(arrays) + ");", "        bool passed = true;"]
    for key in outputs:
        lines += [
            f'        passed = forge_tb::check({key}, golden_{key}, "{key}", "{key}_output.txt") && passed;'
        ]
    lines += [
        "        return passed ? 0 : 1;",
        "    } catch (const std::exception &error) {",
        '        std::fprintf(stderr, "ERROR: %s\\n", error.what());',
        "        return 2;",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def catalog():
    configs, excluded = {}, {}
    for path in sorted(UPSTREAM.glob("*/test_case_configs/*.json")):
        name = path.stem
        try:
            config = json.loads(path.read_text())
        except json.JSONDecodeError as exc:
            # This one upstream file deliberately contains symbolic dimensions.
            if (
                path.relative_to(UPSTREAM).as_posix()
                != "conv/test_case_configs/conv_variable.json"
            ):
                raise
            excluded[str(path.relative_to(UPSTREAM))] = (
                "Symbolic, non-JSON template: " + str(exc)
            )
            continue
        if name in configs:
            raise ValueError(f"Duplicate design name: {name}")
        configs[name] = (path, config)
    return configs, excluded


def effective_config(name, original):
    config = json.loads(json.dumps(original))
    changes = []
    # Complete the declared scalar test output with the dot-product operation
    # already present in testing_impl, using the existing DRAM ports.
    if name in {"testing_impl", "testing_unroll"}:
        ops = config["ops"]
        for key in ["dot_product", "store_2"]:
            ops.pop(key, None)
        for suffix, src, dst, dims in [
            ("9", "DRAM_5", "BRAM_9", [16]),
            ("10", "DRAM_10", "BRAM_10", [16]),
            ("11", "DRAM_11", "BRAM_11", [1]),
        ]:
            ops["load_" + suffix] = {
                "func_name": "load",
                "dims": dims,
                "args": [src, dst],
            }
        ops["dot_product"] = {
            "func_name": "dot_product",
            "dims": [16],
            "func_info": [4, True, False],
            "args": ["BRAM_9", "BRAM_10", "BRAM_11", "BRAM_12"],
        }
        ops["store_2"] = {
            "func_name": "store",
            "dims": [1],
            "args": ["BRAM_12", "DRAM_12"],
        }
        changes.append(
            "Wire DRAM_12 to dot(DRAM_5[:16], DRAM_10[:16]) + DRAM_11[0] using existing ports; add missing loads, compute/store where absent."
        )
    if name in {"resnet50_block3_downsample", "resnet50_block4_downsample"}:
        output_shape = next(
            d["dims"] for d in config["drams"] if d["name"] == "DRAM_image_output"
        )
        for key in ["matrix_add", "activation_3", "store"]:
            config["ops"][key]["dims"] = output_shape.copy()
        changes.append(
            "Match final residual-add, activation, and store channels to the declared full output shape "
            + str(output_shape)
            + "; upstream only processed half the channels."
        )
    if name == "vec_mtx_p2":
        config["ops"]["load_2"]["dims"] = [64]
        changes.append(
            "Load all 64 vector elements required by the 64x16 vector-matrix product; upstream loaded only 16."
        )
    config["data_type"] = "ap_fixed<16,5>"
    return config, changes


@contextlib.contextmanager
def working_directory(path):
    previous = Path.cwd()
    os.chdir(path)
    try:
        yield
    finally:
        os.chdir(previous)


def emit_kernel(domain, config, design):
    spec = importlib.util.spec_from_file_location(
        "forge_emit_" + domain, UPSTREAM / domain / "generate_code.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    if domain == "gemm":
        module.backends.set_current("vitis")
    args = (config["brams"], config["drams"], config["ops"], config["data_type"], "top")
    with working_directory(UPSTREAM / domain):
        source = module.generate_top_function(*args)
        header = module.generate_top_h(config["drams"], config["data_type"], "top")
    (design / "top.cpp").write_text(source)
    (design / "top.h").write_text(header)


def make_inputs(config, seed):
    rng = np.random.default_rng(seed)
    outputs = set(config["output_dram_names"])
    data = {
        d["name"]: rng.integers(-8, 9, size=d["dims"]).astype(float) / 32
        for d in config["drams"]
        if d["name"] not in outputs
    }
    # Follow load edges to identify semantic weight ports without name heuristics.
    origins = {key: key for key in data}
    for op in config["ops"].values():
        fn, args = op["func_name"], op["args"]
        if fn == "load":
            if args[0] in origins:
                origins[args[1]] = origins[args[0]]
        elif fn == "batchnorm":
            weights = data[origins[args[1]]]
            weights[0] = 0.5
            weights[1] = rng.integers(-2, 3, size=weights[1].shape) / 32
            weights[2] = 0
            weights[3] = 1
        elif fn in {"layernorm", "rmsnorm"}:
            key = args[1].split("[")[0]
            data[origins[key]][0] = 0.5
        elif fn == "conv":
            weights = data[origins[args[1]]]
            weights.fill(0)
            cout, cin, kh, kw = weights.shape
            for co in range(cout):
                for ci in {co % cin, (7 * co + 3) % cin}:
                    weights[co, ci] = rng.integers(-2, 3, size=(kh, kw)) / 16
    return data


def golden_outputs(config, data, domain):
    import importlib

    module = importlib.import_module("reference." + domain)
    # NaNs detect missing loads, partial stores, and uncomputed outputs.
    arrays = {
        d["name"]: np.full(d["dims"], np.nan, dtype=np.float64)
        for d in config["brams"] + config["drams"]
    }
    arrays.update({k: v.copy() for k, v in data.items()})
    module.run(config["ops"], arrays)
    result = {k: arrays[k] for k in config["output_dram_names"]}
    for key, value in result.items():
        if not np.isfinite(value).all():
            raise ValueError(f"{key}: nonfinite or unwritten golden output")
    return result


def write_data(path, value):
    np.savetxt(path, value.reshape(-1), fmt="%.17g")


def write_hls(design, config, filenames):
    lines = [
        "open_project -reset project",
        "set_top top",
        "add_files top.cpp",
        "add_files top.h",
    ]
    lines += [
        "add_files -tb " + name
        for name in ["tb_top.cpp", "tb_support.h", *sorted(filenames)]
    ]
    lines += [
        'open_solution "solution1"',
        "set_part {" + config.get("FPGA_name", "xczu9eg-ffvb1156-2-e") + "}",
        "create_clock -period " + str(config.get("clock_period", 10)),
    ]
    (design / "dataset_csim.tcl").write_text(
        "\n".join(lines + ["csim_design -clean", "exit", ""])
    )
    (design / "run_hls.tcl").write_text(
        "\n".join(lines + ["csim_design -clean", "csynth_design", "exit", ""])
    )


def generate(name, path, original, root):
    design = root / name
    design.mkdir(parents=True, exist_ok=True)
    domain = path.parent.parent.name
    config, changes = effective_config(name, original)
    emit_kernel(domain, config, design)
    arrays = interface(design)
    if arrays != {d["name"]: d["dims"] for d in config["drams"]}:
        raise ValueError("Generated top interface differs from config")
    seed = int.from_bytes(hashlib.sha256(name.encode()).digest()[:4], "little")
    data = make_inputs(config, seed)
    golden = golden_outputs(config, data, domain)
    # All numeric files are replaceable fixtures generated by this command.
    for old in design.glob("*.txt"):
        old.unlink()
    inputs = {k: k + ".txt" for k in data}
    outputs = {k: k + ".golden.txt" for k in golden}
    for values, names in [(data, inputs), (golden, outputs)]:
        for key, value in values.items():
            write_data(design / names[key], value)
    (design / "config.json").write_text(json.dumps(config, indent=2) + "\n")
    shutil.copyfile(path, design / "upstream_config.json")
    (design / "tb_top.cpp").write_text(render_testbench(arrays, inputs, outputs))
    shutil.copyfile(HERE / "tb_support.h", design / "tb_support.h")
    filenames = {*inputs.values(), *outputs.values()}
    write_hls(design, config, filenames)
    hashes = {
        f: hashlib.sha256((design / f).read_bytes()).hexdigest()
        for f in sorted(
            filenames
            | {
                "top.cpp",
                "top.h",
                "config.json",
                "upstream_config.json",
                "tb_top.cpp",
                "tb_support.h",
            }
        )
    }
    manifest = {
        "fixture_origin": "python_model",
        "seed": seed,
        "domain": domain,
        "arrays": arrays,
        "inputs": inputs,
        "outputs": outputs,
        "atol": 1e-3,
        "rtol": 0,
        "golden_arithmetic": "float64",
        "kernel_arithmetic": "ap_fixed<16,5>",
        "functional_coverage_complete": True,
        "output_contracts": {k: "python_reference" for k in golden},
        "model": "design_gen_scripts/forgebench/reference/" + domain + ".py",
        "upstream": {k: PROVENANCE[k] for k in ["repository", "branch", "commit"]},
        "upstream_config": str(path.relative_to(UPSTREAM)),
        "config_adjustments": changes,
        "sha256": hashes,
    }
    (design / "testbench.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"{name}: {len(outputs)} checked outputs", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--design", action="append")
    args = parser.parse_args()
    configs, excluded = catalog()
    if args.design:
        unknown = set(args.design) - configs.keys()
        if unknown:
            parser.error(f"Unknown designs: {sorted(unknown)}")
        configs = {k: v for k, v in configs.items() if k in args.design}
    args.root.mkdir(parents=True, exist_ok=True)
    for name, (path, config) in configs.items():
        generate(name, path, config, args.root.resolve())
    (args.root / "suite.json").write_text(
        json.dumps(
            {
                "upstream": {
                    k: PROVENANCE[k] for k in ["repository", "branch", "commit"]
                },
                "designs": sorted(
                    p.parent.name for p in args.root.glob("*/testbench.json")
                ),
                "excluded_configs": excluded,
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
