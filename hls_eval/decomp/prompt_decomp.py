import json
from textwrap import dedent

from hls_eval.prompting import build_input_code_prompt_xml


def build_decompilation_prompt(
    rtl_files: dict[str, str],
    top_function: str,
    hls_clock_period_ns: float,
    hls_fpga_part: str,
    hls_compiler_defines: list[str],
    hls_disable_auto_optimizations: bool,
    hls_unsafe_math: bool,
) -> str:
    prompt = dedent(
        f"""
        ## Overview
        You are an expert FPGA and high-level synthesis engineer. Reconstruct a
        plausible, synthesizable Vitis HLS C++ implementation from the supplied
        RTL generated by Vitis HLS.

        ## Task
        Decompile the RTL into one self-contained C++14 translation unit. The
        implementation must:
        - define the top-level function `{top_function}`;
        - reproduce the RTL module's ports, bit widths, signedness, and control
          interface as closely as possible in HLS C++;
        - use synthesizable constructs supported by Vitis HLS;
        - contain all required declarations and helper functions in the same
          file;
        - not require local headers, source files, a testbench, or a `main`
          function; standard Vitis HLS headers such as `ap_int.h` are allowed;
        - avoid dynamic allocation, recursion, operating-system APIs, file I/O,
          and other non-synthesizable constructs.

        Infer the algorithm and state transitions from all supplied RTL modules,
        including helper modules and ROM initialization data. Prefer clear
        behavioral HLS C++ over manually reproducing the RTL state machine.

        ## Output Format
        Return exactly one XML code element and no explanation:
        <OUTPUT_CODE name="decompiled.cpp">
        // complete standalone HLS C++ implementation
        </OUTPUT_CODE>

        ## RTL Inputs
        """
    ).strip()
    prompt += build_input_code_prompt_xml(rtl_files)
    prompt += "\n## Task Output\n"
    return prompt
