"""Structure of the LaTeX table written by plot_dataflow.py (no LaTeX compiler is
needed or assumed: these check what a compiler would trip over)."""

import re
import sys
from pathlib import Path

import pytest

DIR_EXPERIMENT = (
    Path(__file__).resolve().parent.parent
    / "hls_eval_experiments"
    / "hls_paramaterize_agent_pi"
)
sys.path.insert(0, str(DIR_EXPERIMENT))

plot_dataflow = pytest.importorskip("plot_dataflow")

RESOURCES = list(plot_dataflow.RESOURCE_TYPES)


def scores(no_tools, tools):
    return {"no_tools": no_tools, "tools": tools}


def all_resources(pair):
    return {key: pair for key in RESOURCES}


@pytest.fixture
def tex(tmp_path):
    rows = [
        (
            "k7mmseq_balanced",
            all_resources(scores(0.47, 0.98)),
            {"no_tools": 1530.0, "tools": 4290.0},  # 25.5 and 71.5 minutes
        ),
        (
            "atax",
            {
                RESOURCES[0]: scores(0.97, 0.85),
                RESOURCES[1]: scores(0.87, 0.87),  # tie: nothing bold
                RESOURCES[2]: scores(float("nan"), 0.5),  # a run without a front
                RESOURCES[3]: None,  # not scored
            },
            {"no_tools": 600.0, "tools": None},  # no time recorded for the tools run
        ),
    ]
    path = tmp_path / "out" / "dataflow_results.tex"
    plot_dataflow.write_results_tex(rows, 0, path, excluded=["ResMLP", "gemm"])
    return path.read_text()


def body_rows(text):
    return [
        line
        for line in text.splitlines()
        if line.endswith(r"\\") and "Latency vs." in line
    ]


def test_environments_are_balanced_and_rules_are_present(tex):
    assert tex.count(r"\begin{tabular}") == tex.count(r"\end{tabular}") == 1
    for command in (r"\toprule", r"\midrule", r"\bottomrule", r"\cmidrule(lr){3-4}"):
        assert command in tex
    assert re.search(r"\\begin\{tabular\}\{llcccc\}", tex)
    assert r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}" in tex
    assert r"\usepackage{booktabs,multirow}" in tex


def test_every_row_has_six_cells_and_each_design_has_one_row_per_resource(tex):
    rows = body_rows(tex)
    assert len(rows) == 2 * len(RESOURCES)
    assert all(row.count("&") == 5 for row in rows)
    for design in (r"k7mmseq\_balanced", "atax"):
        assert tex.count(rf"\multirow{{{len(RESOURCES)}}}{{*}}{{{design}}}") == 1


def test_names_are_escaped_and_columns_are_no_tools_then_tools(tex):
    assert "k7mmseq_balanced" not in tex.replace(r"\_", "")  # only the escaped form
    first = body_rows(tex)[0]
    assert first.split("&")[2].strip() == "0.47"  # No tools
    assert first.split("&")[3].strip().startswith(r"\textbf{0.98}")  # Tools, higher


def test_bold_marks_only_the_higher_score_and_missing_scores_are_dashes(tex):
    atax = [row for row in body_rows(tex)][len(RESOURCES) :]
    assert r"\textbf{0.97}" in atax[0] and r"\textbf{0.85}" not in atax[0]
    assert r"\textbf" not in atax[1]  # tie
    assert atax[2].split("&")[2].strip() == "--"  # NaN
    assert r"\textbf" not in atax[2]
    assert atax[3].split("&")[2].strip() == "--"
    assert atax[3].split("&")[3].strip().rstrip("\\").strip() == "--"


def test_runtime_columns_span_the_rows_of_a_design_with_one_number_each(tex):
    rows = body_rows(tex)
    n = len(RESOURCES)
    first, later = rows[0].split("&"), rows[1].split("&")
    assert first[4].strip() == rf"\multirow{{{n}}}{{*}}{{25.5}}"  # No tools, minutes
    assert first[5].strip().startswith(rf"\multirow{{{n}}}{{*}}{{71.5}}")  # Tools
    assert later[4].strip() == "" and later[5].strip().rstrip("\\").strip() == ""
    # a missing runtime is a dash, still spanning the design's rows
    atax_first = rows[n].split("&")
    assert atax_first[4].strip() == rf"\multirow{{{n}}}{{*}}{{10.0}}"
    assert atax_first[5].strip().startswith(rf"\multirow{{{n}}}{{*}}{{--}}")
    assert "Agent runtime (min)" in tex
    assert "NOT included" in tex  # the comment says evaluation time is excluded


def test_designs_left_out_by_choice_are_noted_in_the_header(tmp_path):
    path = tmp_path / "t.tex"
    row = ("atax", all_resources(scores(0.5, 0.6)), {"no_tools": 60.0, "tools": 120.0})
    plot_dataflow.write_results_tex(
        [row], 0, path, excluded=[], omitted=["MultiHeadSelfAttention1"]
    )
    text = path.read_text()
    assert "% Left out of this table by choice: MultiHeadSelfAttention1" in text
    assert "MultiHeadSelfAttention1" not in "".join(
        line for line in text.splitlines() if not line.startswith("%")
    )


def test_multi_head_attention_is_excluded_from_the_table_by_default():
    assert "MultiHeadSelfAttention1" in plot_dataflow.TABLE_EXCLUDED_DESIGNS


def test_header_comment_lists_excluded_designs(tex):
    assert tex.startswith("% Generated by plot_dataflow.py")
    assert "Not included (iteration 0 missing in a run): ResMLP, gemm" in tex


def test_latex_escape_covers_the_special_characters():
    assert plot_dataflow._latex_escape("a_b&c%d$e#f{g}") == r"a\_b\&c\%d\$e\#f\{g\}"


def test_scores_use_the_same_function_as_the_plots():
    """The table's numbers come from case_scores, which the plots also use."""
    import inspect

    assert "case_scores(iterations_by_run)" in inspect.getsource(plot_dataflow.make_plot)
